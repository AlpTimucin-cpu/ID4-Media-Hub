/** These files are generated by :nativecockpit:generateOriginalEngineWavAssets. */
enum class EngineProfile(val label: String, val idle: Int, val accel: Int) {
    V8("V8", R.raw.v8_idle, R.raw.v8_accel),
    F1("F1", R.raw.f1_idle, R.raw.f1_accel),
    Futuristic("Futuristic", R.raw.futuristic_idle, R.raw.futuristic_accel),
    Turbine("Turbine", R.raw.turbine_idle, R.raw.turbine_accel),
    Stealth("Stealth", R.raw.stealth_idle, R.raw.stealth_accel);
    companion object {
        fun from(value: String): EngineProfile = entries.firstOrNull {
            it.name == value
        } ?: V8
    }
}

/** Optional in-cabin sound. Real, recent OBD speed is required for automatic playback. */
@Singleton
class ActiveSoundManager @Inject constructor(
    @ApplicationContext private val context: Context
) {
    private val tag = "EV-Cockpit-ActiveSound"
    private val main = Handler(Looper.getMainLooper())
    private var idle: ExoPlayer? = null
    private var acceleration: ExoPlayer? = null
    private var currentProfile: EngineProfile? = null
    private var lastSpeedKmh: Double? = null
    private var lastSpeedAtMs: Long? = null
    private var smoothRate = 1.0f
    private var smoothPitch = 1.0f
    private var enabled = false
    private var volume = 1f
    private var ducked = false
    private var previewing = false
    private var previewToken = 0L
    private var activeInForeground = false
    private var lastLoggedReason: String? = null
    private val unavailable = MutableStateFlow(false)
    val audioUnavailable: StateFlow<Boolean> = unavailable.asStateFlow()

    private fun status(reason: String) {
        if (reason != lastLoggedReason) {
            Log.i(tag, reason)
            lastLoggedReason = reason
        }
    }

    private fun createPlayer(resourceId: Int): ExoPlayer? {
        var candidate: ExoPlayer? = null
        return try {
            if (resourceId == 0) throw Resources.NotFoundException("0 resource ID")
            // A successful compilation does not guarantee a readable media asset.
            context.resources.openRawResource(resourceId).use { input ->
                if (input.read() == -1) error("Empty WAV asset")
            }
            candidate = ExoPlayer.Builder(context).build()
            candidate.apply {
                setAudioAttributes(
                    AudioAttributes.Builder()
                        .setUsage(C.USAGE_MEDIA)
                        .setContentType(C.AUDIO_CONTENT_TYPE_MUSIC)
                        .build(), false
                )
                setHandleAudioBecomingNoisy(true)
                addListener(object : Player.Listener {
                    override fun onPlayerError(error: PlaybackException) {
                        unavailable.value = true
                        Log.e(tag, "Ses dosyası eksik veya çözücü dosyayı okuyamadı", error)
                        pausePlayers()
                    }
                })
                setMediaItem(MediaItem.fromUri(
                    Uri.parse("android.resource://${context.packageName}/$resourceId")
                ))
                repeatMode = Player.REPEAT_MODE_ONE
                prepare()
            }
        } catch (error: Resources.NotFoundException) {
            unavailable.value = true
            Log.e(tag, "Ses dosyası eksik (raw id=$resourceId)", error)
            runCatching { candidate?.release() }
            null
        } catch (error: Exception) {
            unavailable.value = true
            Log.e(tag, "Ses dosyası eksik, boş veya oynatılamıyor (raw id=$resourceId)", error)
            runCatching { candidate?.release() }
            null
        }
    }

    /**
     * User-provided res/raw/engine_idle.* and engine_accel.* take precedence
     * for V8. They are OPTIONAL: referencing R.raw.engine_idle would fail
     * compilation when no file has been uploaded, so resolve at runtime.
     */
    @Suppress("DiscouragedApi")
    private fun soundIds(profile: EngineProfile): Pair<Int, Int> {
        if (profile == EngineProfile.V8) {
            val ownIdle = context.resources.getIdentifier(
                "engine_idle", "raw", context.packageName
            )
            val ownAccel = context.resources.getIdentifier(
                "engine_accel", "raw", context.packageName
            )
            if (ownIdle != 0 && ownAccel != 0) return ownIdle to ownAccel
        }
        // Existing generated WAV assets remain the non-crashing fallback.
        return profile.idle to profile.accel
    }

    private fun selectProfile(profile: EngineProfile): Boolean {
        if (profile == currentProfile && idle != null && acceleration != null) return true
        runCatching { idle?.release() }
        runCatching { acceleration?.release() }
        idle = null
        acceleration = null
        val (idleResource, accelResource) = soundIds(profile)
        idle = createPlayer(idleResource)
        acceleration = createPlayer(accelResource)
        if (idle == null || acceleration == null) {
            runCatching { idle?.release() }
            runCatching { acceleration?.release() }
            idle = null
            acceleration = null
            currentProfile = null
            Log.w(tag, "Ses dosyası eksik: ${profile.name} profili sessiz kalacak")
            return false
        }
        currentProfile = profile
        unavailable.value = false
        return true
    }

    fun update(
        settings: UserSettings,
        speedKmh: Double?,
        speedAtMs: Long?,
        foreground: Boolean
    ) {
        main.post {
            activeInForeground = foreground
            enabled = settings.isEngineSoundEnabled
            volume = settings.engineVolume.coerceIn(0f, 1.5f)
            val now = System.currentTimeMillis()
            val speed = speedKmh?.takeIf { it.isFinite() && it in 0.0..300.0 }
            val fresh = speedAtMs != null && now - speedAtMs in 0L..10_000L
            val reason = when {
                !foreground -> "Motor sesi: uygulama arka planda"
                !enabled -> "Motor sesi: ayarlardan kapalı"
                previewing -> "Motor sesi: önizleme oynuyor"
                speed == null -> "Motor sesi: OBD hızı yok"
                !fresh -> "Motor sesi: OBD hızı eski"
                else -> "Motor sesi: canlı OBD hızı alınıyor"
            }
            status(reason)
            if (!foreground || !enabled || previewing || speed == null || !fresh) {
                if (!previewing) pausePlayers()
                return@post
            }
            val stamp = speedAtMs ?: return@post
            if (!selectProfile(EngineProfile.from(settings.engineSoundProfile))) return@post
            if (lastSpeedAtMs == stamp) {
                applyVolumes()
                return@post
            }
            val deltaSeconds = lastSpeedAtMs?.let {
                (stamp - it).toDouble() / 1_000.0
            } ?: 0.0
            val decision = EngineMotionPolicy.decide(speed, lastSpeedKmh, deltaSeconds)
            lastSpeedKmh = speed
            lastSpeedAtMs = stamp
            runCatching {
                // Both speed and pitch depend on the last genuine OBD speed.
                val playbackRate = (0.90f + (speed / 300.0).toFloat())
                    .coerceIn(0.90f, 1.30f)
                // One-pole smoothing avoids abrupt "game effect" pitch jumps.
                smoothRate += (playbackRate - smoothRate) * 0.28f
                smoothPitch += (decision.pitch.coerceIn(.90f, 1.38f) - smoothPitch) * .22f
                acceleration?.playbackParameters = PlaybackParameters(
                    smoothRate, smoothPitch
                )
                idle?.playbackParameters = PlaybackParameters(
                    smoothRate.coerceIn(.90f, 1.10f),
                    smoothPitch.coerceIn(.90f, 1.10f)
                )
                when (decision.mode) {
                    EngineMotionPolicy.Mode.ACCELERATING -> {
                        idle?.pause(); acceleration?.play()
                    }
                    EngineMotionPolicy.Mode.IDLE -> {
                        acceleration?.pause(); idle?.play()
                    }
                    EngineMotionPolicy.Mode.SILENT -> pausePlayers()
                }
                applyVolumes()
            }.onFailure {
                Log.e(tag, "Motor sesi güncellenemedi", it)
                unavailable.value = true
                pausePlayers()
            }
        }
    }

    fun setSpeechDucking(active: Boolean) {
        main.post { ducked = active; applyVolumes() }
    }

    private fun applyVolumes() {
        val level = (volume / 1.5f).coerceIn(0f, 1f)
        val speechFactor = if (ducked) .2f else 1f
        val motionFactor = if (previewing) 1f else
            (0.55f + ((lastSpeedKmh ?: 0.0) / 180.0).toFloat())
                .coerceIn(0.55f, 1f)
        runCatching { idle?.volume = level * speechFactor * motionFactor * .75f }
        runCatching { acceleration?.volume = level * speechFactor * motionFactor }
    }

    /** Three-second preview requires no OBD speed, but only runs in foreground. */
    fun preview(settings: UserSettings) {
        main.post {
            if (!activeInForeground) {
                status("Önizleme engellendi: uygulama arka planda")
                return@post
            }
            previewToken++
            val token = previewToken
            previewing = true
            volume = settings.engineVolume.coerceIn(0f, 1.5f)
            if (!selectProfile(EngineProfile.from(settings.engineSoundProfile))) {
                previewing = false
                return@post
            }
            runCatching {
                idle?.pause()
                acceleration?.playbackParameters = PlaybackParameters(1f, 1.25f)
                acceleration?.play()
                applyVolumes()
                Log.i(tag, "Motor sesi önizlemesi başladı")
            }.onFailure {
                Log.e(tag, "Motor sesi önizlemesi başarısız", it)
                previewing = false
                pausePlayers()
                return@post
            }
            main.postDelayed({
                if (previewToken == token) {
                    previewing = false
                    pausePlayers()
                }
            }, 3_000L)
        }
    }

    private fun pausePlayers() {
        runCatching { idle?.pause() }
        runCatching { acceleration?.pause() }
        lastSpeedKmh = null
        lastSpeedAtMs = null
        smoothRate = 1f
        smoothPitch = 1f
    }

    fun onResume() { main.post { activeInForeground = true } }
    fun onPause() {
        main.post {
            activeInForeground = false
            previewing = false
            previewToken++
            pausePlayers()
        }
    }

    fun release() {
        main.post {
            pausePlayers()
            runCatching { idle?.release() }
            runCatching { acceleration?.release() }
            idle = null
            acceleration = null
            currentProfile = null
        }
    }
}